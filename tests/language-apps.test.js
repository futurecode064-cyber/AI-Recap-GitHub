'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ROOT=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const json=p=>JSON.parse(read(p));
const site=read('portal/apps/index.html');
const releases=json('portal/apps/latest.json').apps;
const required=['english-academy','thai-speaking','chinese-learning','language-academy'];
const cards=[...site.matchAll(/<article\b[\s\S]*?<\/article>/g)].map(m=>m[0]);
let checks=0;
for(const key of required){
 const card=cards.find(c=>c.includes('data-app="'+key+'"'));
 assert.ok(card,'Missing language APK: '+key);
 assert.match(card,/data-category="language"/);
 assert.match(card,new RegExp('data-app-key="'+key+'"'));
 const records=releases.filter(r=>r.id===key);
 assert.equal(records.length,1,'Exactly one release metadata record for '+key);
 assert.match(records[0].sha256,/^[0-9a-f]{64}$/);
 assert.ok(records[0].versionCode>=1);
 const link=(card.match(/class="download"[^>]+href="([^"]+)"/)||[])[1] ||
   (card.match(/href="([^"]+)"[^>]*class="download"/)||[])[1];
 assert.ok(link,'Missing direct APK download for '+key);
 const expected=new URL(records[0].file,'https://example.invalid/AI-Recap-GitHub/apps/').href;
 assert.equal(new URL(link,'https://example.invalid/AI-Recap-GitHub/apps/').href,expected);
 checks++;
}
assert.equal(new Set(releases.map(x=>x.id)).size,releases.length,'Duplicate release IDs');
const apk=fs.readFileSync(path.join(ROOT,'portal/apps/Future_Code_English_Academy_v1.0.0.apk'));
assert.ok(apk.length>100000&&apk[0]===80&&apk[1]===75,'English APK archive missing');
checks++;
const thaiCode=read('portal/thai-course/course.js');
new vm.Script(thaiCode,{filename:'thai-course.js'});
const si=thaiCode.indexOf('const course=[');
assert.ok(si>=0);
const thai=Function(thaiCode.slice(si,thaiCode.indexOf('];',si)+2)+' return course;')();
assert.equal(thai.length,6);
assert.equal(thai.reduce((n,l)=>n+l[3].length,0),18);
for(const l of thai)assert.equal(l[3].length,3);
checks++;
const ctx={window:{}};
vm.runInNewContext(read('chinese-learning/app/src/main/assets/course.js'),ctx);
const chinese=ctx.window.FC_COURSE;
assert.equal(chinese.length,6);
assert.equal(chinese.reduce((n,l)=>n+l.units.length,0),24);
assert.equal(chinese.reduce((n,l)=>n+l.units.reduce((m,u)=>m+u.words.length,0),0),192);
new vm.Script(read('chinese-learning/app/src/main/assets/app.js'));
checks++;
const academyHtml=read('portal/apps/languages/index.html');
const inline=[...academyHtml.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)];
assert.equal(inline.length,1);
new vm.Script(inline[0][1]);
const mi=inline[0][1].indexOf('const languages=[');
assert.ok(mi>=0);
const languages=Function(inline[0][1].slice(mi,inline[0][1].indexOf('];',mi)+2)+' return languages;')();
assert.equal(languages.length,12);
assert.equal(new Set(languages.map(l=>l[0])).size,12);
for(const l of languages)assert.equal(l[4].length,18);
assert.match(academyHtml,/id="restore"/);
checks++;
const manifest=json('portal/apps/languages/latest.json');
const thaiLatest=json('portal/thai-course/latest.json');
const chineseLatest=json('portal/apps/chinese-update.json');
const version=(id)=>releases.find(x=>x.id===id);
assert.equal(version('chinese-learning').versionCode,chineseLatest.versionCode);
assert.equal(version('thai-speaking').versionCode,thaiLatest.versionCode);
assert.equal(version('language-academy').versionCode,manifest.versionCode);
assert.equal(version('language-academy').sha256,manifest.sha256);
assert.equal(version('thai-speaking').sha256,thaiLatest.sha256);
assert.match(read('chinese-learning/app/build.gradle'),/versionCode 4[\s\S]*versionName '1\.0\.3'/);
assert.match(read('thai-course/app/build.gradle'),/versionCode 3[\s\S]*versionName '1\.0\.2'/);
assert.match(read('language-apk/AndroidManifest.xml'),/versionCode="3" android:versionName="1.0.2"/);
checks++;
for(const file of ['.github/workflows/future-code-thai-apk.yml','.github/workflows/fc-language-academy-apk.yml']){
 const workflow=read(file);
 assert.match(workflow,/id-token: write/);
 assert.match(workflow,/apksigner" verify|apksigner"\s+verify/);
 assert.match(workflow,/OIDC=/);
 assert.ok(!workflow.includes('echo "$ANDROID_KEYSTORE_PASS"'));
}
checks++;
console.log('PASS '+checks+' language APK checks: 4 release cards, 4 links, 6/18 Thai, 6/24/192 Chinese, 12-language academy with 18 phrases each, Android versions and secured release workflows.');
